#!/usr/bin/env bash
# One-time KRaft setup for the 2-node A2 cluster: writes this node's config, wipes + formats
# its storage, opens the firewall on the ZeroTier interface, and starts Kafka.
#
#   VM2:  bash kafka_node_setup.sh vm2 <VM2_IP> <VM2_IP> <CLUSTER_ID>     (run first)
#   VM3:  bash kafka_node_setup.sh vm3 <VM2_IP> <VM3_IP> <CLUSTER_ID>
#
# CLUSTER_ID: run `$KAFKA_HOME/bin/kafka-storage.sh random-uuid` ONCE and pass the SAME value on both VMs.
# WARNING: deletes $KAFKA_HOME/data/kraft on this VM (the old single-node demo topics).
set -euo pipefail
ROLE=${1:?vm2|vm3} VM2_IP=${2:?VM2_IP} SELF_IP=${3:?this VM ZeroTier IP} CID=${4:?CLUSTER_ID}
KAFKA_HOME=${KAFKA_HOME:-/opt/kafka}
DATA=$KAFKA_HOME/data/kraft
CONF=$KAFKA_HOME/config/a2-kraft.properties

case $ROLE in
  vm2) NODE_ID=1 ROLES=broker,controller
       LISTENERS="PLAINTEXT://:9092,CONTROLLER://:9093"
       ADVERTISED="PLAINTEXT://$SELF_IP:9092,CONTROLLER://$SELF_IP:9093" ;;
  vm3) NODE_ID=2 ROLES=broker
       LISTENERS="PLAINTEXT://:9092"
       ADVERTISED="PLAINTEXT://$SELF_IP:9092" ;;
  *) echo "first argument must be vm2 or vm3"; exit 1 ;;
esac

if jps | grep -qw Kafka; then
  echo "Kafka is already running here. Stop it first: $KAFKA_HOME/bin/kafka-server-stop.sh"; exit 1
fi

cat > "$CONF" <<EOF
# A2 KRaft config for $ROLE - generated by kafka_node_setup.sh
process.roles=$ROLES
node.id=$NODE_ID
controller.quorum.voters=1@$VM2_IP:9093
controller.listener.names=CONTROLLER
listeners=$LISTENERS
advertised.listeners=$ADVERTISED
inter.broker.listener.name=PLAINTEXT
listener.security.protocol.map=CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT
log.dirs=$DATA
num.partitions=2
default.replication.factor=2
min.insync.replicas=1
offsets.topic.replication.factor=2
transaction.state.log.replication.factor=2
transaction.state.log.min.isr=1
auto.create.topics.enable=false
EOF
echo "wrote $CONF"

ZT_IF=$(ip -o -4 addr show | awk -v ip="$SELF_IP" 'index($4, ip "/") == 1 {print $2}')
if [ -z "$ZT_IF" ]; then echo "no interface has IP $SELF_IP - check the ZeroTier IP (ip a)"; exit 1; fi
if command -v ufw >/dev/null && sudo ufw status | grep -q "Status: active"; then
  sudo ufw allow in on "$ZT_IF" to any port 9092 proto tcp
  if [ "$ROLE" = vm2 ]; then sudo ufw allow in on "$ZT_IF" to any port 9093 proto tcp; fi
fi

rm -rf "$DATA" && mkdir -p "$DATA"
"$KAFKA_HOME/bin/kafka-storage.sh" format -t "$CID" -c "$CONF"
"$KAFKA_HOME/bin/kafka-server-start.sh" -daemon "$CONF"
sleep 8
jps | grep -w Kafka && echo "Kafka started as node $NODE_ID ($ROLES)" \
  || { echo "Kafka did not start - see: tail -50 $KAFKA_HOME/logs/server.log"; exit 1; }
